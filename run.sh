#!/bin/bash
# ============================================================
# APEX JAILBREAK v4.0 - RUN.SH
# Запуск 17 эксплойтов на устройстве
# ============================================================

set -e

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m'

# ============================================================
# ЗАГОЛОВОК
# ============================================================

clear
echo -e "${CYAN}"
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║                                                              ║"
echo "║     █████  ██████  ███████ ██   ██  ██████  ███████        ║"
echo "║    ██   ██ ██   ██ ██      ██   ██ ██    ██ ██             ║"
echo "║    ███████ ██████  ███████ ███████ ██    ██ ███████        ║"
echo "║    ██   ██ ██   ██      ██ ██   ██ ██    ██      ██        ║"
echo "║    ██   ██ ██   ██ ███████ ██   ██  ██████  ███████        ║"
echo "║                                                              ║"
echo "║           ═══ APEX JAILBREAK v4.0 ═══                       ║"
echo "║           ═══ RUN SCRIPT ═══                                ║"
echo "║                                                              ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo -e "${NC}"

# ============================================================
# ПРОВЕРКИ
# ============================================================

echo -e "\n${YELLOW}[!] Проверка окружения...${NC}"

# Проверка прав
if [[ $EUID -ne 0 ]]; then
    echo -e "${YELLOW}[!] Запуск без root. Некоторые эксплойты могут не сработать.${NC}"
    echo -e "${YELLOW}[!] Рекомендуется: sudo ./run.sh${NC}"
fi

# Проверка наличия бинарника
if [[ ! -f "./apex_jailbreak" ]]; then
    echo -e "${RED}[-] Бинарник apex_jailbreak не найден!${NC}"
    echo -e "${YELLOW}[!] Сначала соберите проект: ./build.sh${NC}"
    exit 1
fi

# Проверка архитектуры
ARCH=$(file ./apex_jailbreak | grep -o "arm64\|x86_64\|armv7" | head -1)
if [[ -z "$ARCH" ]]; then
    ARCH="unknown"
fi
echo -e "${GREEN}[+] Архитектура: $ARCH${NC}"

# Проверка устройства
if command -v ideviceinfo &> /dev/null; then
    DEVICE_NAME=$(ideviceinfo -k DeviceName 2>/dev/null || echo "unknown")
    IOS_VERSION=$(ideviceinfo -k ProductVersion 2>/dev/null || echo "unknown")
    echo -e "${GREEN}[+] Устройство: $DEVICE_NAME${NC}"
    echo -e "${GREEN}[+] iOS версия: $IOS_VERSION${NC}"
else
    echo -e "${YELLOW}[!] ideviceinfo не найден. Установите libimobiledevice.${NC}"
fi

# ============================================================
# ВЫБОР РЕЖИМА
# ============================================================

echo -e "\n${YELLOW}════════════════════════════════════════════════════════════${NC}"
echo -e "${YELLOW}  ВЫБЕРИТЕ РЕЖИМ ЗАПУСКА:${NC}"
echo -e "${YELLOW}════════════════════════════════════════════════════════════${NC}"
echo -e "${GREEN}  1)${NC} Полный джейлбрейк (все 17 эксплойтов)"
echo -e "${GREEN}  2)${NC} Быстрый джейлбрейк (только основные эксплойты)"
echo -e "${GREEN}  3)${NC} Только утечка KASLR и root"
echo -e "${GREEN}  4)${NC} Только отключение AMFI"
echo -e "${GREEN}  5)${NC} Тестовый запуск (без изменений)"
echo -e "${GREEN}  6)${NC} Выход"
echo ""

read -p "Выберите режим [1-6]: " MODE

case $MODE in
    1)
        MODE_NAME="ПОЛНЫЙ ДЖЕЙЛБРЕЙК"
        ARGS=""
        ;;
    2)
        MODE_NAME="БЫСТРЫЙ ДЖЕЙЛБРЕЙК"
        ARGS="--fast"
        ;;
    3)
        MODE_NAME="ТОЛЬКО KASLR + ROOT"
        ARGS="--kaslr-root"
        ;;
    4)
        MODE_NAME="ТОЛЬКО AMFI"
        ARGS="--amfi-only"
        ;;
    5)
        MODE_NAME="ТЕСТОВЫЙ ЗАПУСК"
        ARGS="--test"
        ;;
    6)
        echo -e "${YELLOW}[!] Выход${NC}"
        exit 0
        ;;
    *)
        echo -e "${RED}[-] Неверный выбор!${NC}"
        exit 1
        ;;
esac

echo -e "\n${GREEN}[+] Режим: $MODE_NAME${NC}"

# ============================================================
# ПОДГОТОВКА
# ============================================================

echo -e "\n${YELLOW}[!] Подготовка к запуску...${NC}"

# Создание директории для логов
mkdir -p ./logs
LOG_FILE="./logs/apex_$(date +%Y%m%d_%H%M%S).log"
echo -e "${GREEN}[+] Лог файл: $LOG_FILE${NC}"

# Копирование Python скрипта
if [[ -f "./src/3exploit.py" ]]; then
    cp ./src/3exploit.py ./3exploit.py
    chmod +x ./3exploit.py
    echo -e "${GREEN}[+] 3exploit.py скопирован${NC}"
fi

# ============================================================
# ЗАПУСК
# ============================================================

echo -e "\n${YELLOW}════════════════════════════════════════════════════════════${NC}"
echo -e "${YELLOW}  ЗАПУСК ДЖЕЙЛБРЕЙКА${NC}"
echo -e "${YELLOW}════════════════════════════════════════════════════════════${NC}"
echo -e "${RED}[!] НЕ ОТКЛЮЧАЙТЕ УСТРОЙСТВО!${NC}"
echo -e "${RED}[!] НЕ НАЖИМАЙТЕ CTRL+C!${NC}"
echo ""

# Спросить подтверждение
read -p "Продолжить? (y/n): " CONFIRM
if [[ "$CONFIRM" != "y" && "$CONFIRM" != "Y" ]]; then
    echo -e "${YELLOW}[!] Отмена${NC}"
    exit 0
fi

# Запуск с логированием
echo -e "\n${GREEN}[+] Запуск: ./apex_jailbreak $ARGS${NC}"
echo -e "${GREEN}[+] Логирование в: $LOG_FILE${NC}"
echo ""

# Выполнение
if [[ "$MODE" == "5" ]]; then
    # Тестовый режим
    echo -e "${YELLOW}[!] ТЕСТОВЫЙ РЕЖИМ - ИЗМЕНЕНИЙ НЕ БУДЕТ${NC}"
    ./apex_jailbreak $ARGS --dry-run 2>&1 | tee -a "$LOG_FILE"
else
    # Реальный запуск
    ./apex_jailbreak $ARGS 2>&1 | tee -a "$LOG_FILE"
fi

# Проверка результата
EXIT_CODE=$?
if [[ $EXIT_CODE -eq 0 ]]; then
    echo -e "\n${GREEN}════════════════════════════════════════════════════════════${NC}"
    echo -e "${GREEN}  ✅ ДЖЕЙЛБРЕЙК УСПЕШНО ЗАВЕРШЁН!${NC}"
    echo -e "${GREEN}════════════════════════════════════════════════════════════${NC}"
else
    echo -e "\n${RED}════════════════════════════════════════════════════════════${NC}"
    echo -e "${RED}  ❌ ДЖЕЙЛБРЕЙК НЕ УДАЛСЯ!${NC}"
    echo -e "${RED}  Код ошибки: $EXIT_CODE${NC}"
    echo -e "${RED}════════════════════════════════════════════════════════════${NC}"
    echo -e "${YELLOW}[!] Проверьте лог: $LOG_FILE${NC}"
    exit $EXIT_CODE
fi

# ============================================================
# ПОСТ-ОБРАБОТКА
# ============================================================

echo -e "\n${YELLOW}[!] Пост-обработка...${NC}"

# Проверка root
if [[ $EUID -eq 0 ]]; then
    echo -e "${GREEN}[+] Запуск с root правами${NC}"
fi

# Очистка
if [[ -f "./3exploit.py" ]]; then
    rm -f ./3exploit.py
    echo -e "${GREEN}[+] Очистка завершена${NC}"
fi

# ============================================================
# ФИНАЛ
# ============================================================

echo -e "\n${CYAN}╔════════════════════════════════════════════════════════════╗${NC}"
echo -e "${CYAN}║  ГОТОВО, БЛЯДЬ!                                         ║${NC}"
echo -e "${CYAN}║  Лог: $LOG_FILE${NC}"
echo -e "${CYAN}║  Устройство взломано!                                   ║${NC}"
echo -e "${CYAN}╚════════════════════════════════════════════════════════════╝${NC}"
echo ""

# Справка по дальнейшим действиям
echo -e "${YELLOW}════════════════════════════════════════════════════════════${NC}"
echo -e "${YELLOW}  ДАЛЬНЕЙШИЕ ДЕЙСТВИЯ:${NC}"
echo -e "${YELLOW}════════════════════════════════════════════════════════════${NC}"
echo -e "${GREEN}  1.${NC} Установите Cydia:    ./install_cydia.sh"
echo -e "${GREEN}  2.${NC} Установите Sileo:    ./install_sileo.sh"
echo -e "${GREEN}  3.${NC} Установите SSH:      apt-get install openssh"
echo -e "${GREEN}  4.${NC} Просмотр лога:       cat $LOG_FILE"
echo -e "${GREEN}  5.${NC} Перезагрузка:        reboot"
echo ""

# ============================================================
# СПРАВКА
# ============================================================

if [[ "$1" == "--help" || "$1" == "-h" ]]; then
    echo "Использование: ./run.sh [опции]"
    echo ""
    echo "Опции:"
    echo "  --help, -h    Показать справку"
    echo ""
    echo "Интерактивный режим:"
    echo "  1 - Полный джейлбрейк"
    echo "  2 - Быстрый джейлбрейк"
    echo "  3 - Только KASLR + root"
    echo "  4 - Только AMFI"
    echo "  5 - Тестовый режим"
    echo "  6 - Выход"
    exit 0
fi